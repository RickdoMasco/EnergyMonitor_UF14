BEGIN;

CREATE TABLE IF NOT EXISTS sensor_simulators (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address varchar(255),
    mac_address varchar(255),
    functioning boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS quantities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_quantities_name_ci
    ON quantities (lower(name));

CREATE TABLE IF NOT EXISTS measurements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    simulator_id bigint NOT NULL REFERENCES sensor_simulators (id),
    quantity_id bigint NOT NULL REFERENCES quantities (id),
    measurement_value double precision NOT NULL,
    unit varchar(32) NOT NULL,
    measured_at timestamp with time zone NOT NULL
);

COMMIT;
